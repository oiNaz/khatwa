export type MessageKey = keyof typeof translations.en

export function translate(language: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  let message: string = translations[language][key] ?? translations.en[key]
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, String(value))
  }
  return message
}
